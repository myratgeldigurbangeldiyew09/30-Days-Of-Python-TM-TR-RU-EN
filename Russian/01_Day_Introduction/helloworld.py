# День 1 - Челлендж 30DaysOfPython

print("Привет, мир!")  # Вывод фразы Привет, мир!

# Математические операции
print(2 + 3)   # Сложение (+)
print(3 - 1)   # Вычитание (-)
print(2 * 3)   # Умножение (*)
print(3 / 2)   # Деление (/)
print(3 ** 2)  # Возведение в степень (**)
print(3 % 2)   # Остаток от деления (%)
print(3 // 2)  # Целочисленное деление (Floor division)

# Проверка типов данных (Data types)
print(type(10))                  # Целое число (Int)
print(type(3.14))                # Число с плавающей точкой (Float)
print(type(1 + 3j))              # Комплексное число (Complex)
print(type('Myrat'))             # Строка (String)
print(type([1, 2, 3]))           # Список (List)
print(type({'name': 'Myrat'}))   # Словарь (Dictionary)
print(type({9.8, 3.14, 2.7}))    # Множество (Set)
print(type((9.8, 3.14, 2.7)))    # Кортеж (Tuple)
