print("Merhaba Dünya!")  # Ekrana Merhaba Dünya yazdırır

# Matematiksel İşlemler
print(2 + 3)   # Toplama (+)
print(3 - 1)   # Çıkarma (-)
print(2 * 3)   # Çarpma (*)
print(3 / 2)   # Bölme (/)
print(3 ** 2)  # Üs alma (**)
print(3 % 2)   # Mod alma / Kalan (%)
print(3 // 2)  # Tam bölme (Floor division)

# Veri Tiplerini Kontrol Etme (Data types)
print(type(10))                  # Tam sayı (Int)
print(type(3.14))                # Ondalıklı sayı (Float)
print(type(1 + 3j))              # Karmaşık sayı (Complex)
print(type('Myrat'))             # Metin (String)
print(type([1, 2, 3]))           # Liste (List)
print(type({'name': 'Myrat'}))   # Sözlük (Dictionary)
print(type({9.8, 3.14, 2.7}))    # Küme (Set)
print(type((9.8, 3.14, 2.7)))    # Demet (Tuple)
